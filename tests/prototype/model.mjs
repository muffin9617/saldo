import assert from 'node:assert/strict';
const M=await import(process.env.SALDO_PRODUCTION_MODEL==='1'?'../../dist/ledger-model.js':'../../prototype/model.mjs');
import {createFixtures} from '../../prototype/fixtures.mjs';

let state=createFixtures();const original=structuredClone(state),day=M.today();
const get=id=>state.records.find(r=>r.id===id);
const initial=M.summary(state);
assert.equal(initial.balance,108000n);
assert.equal(initial.equivalent,29667n); // 30 + 100 + 2000/12 rounded to cents.
assert.equal(initial.excluded,2);
assert.equal(initial.forecast,123000n);
assert.equal(M.recordPaid(state,'spa'),200000n);
state=M.applyOperation(state,'spa',{type:'use',date:day,values:{'spa-body':100}},1);
assert.equal(get('spa').entitlements[0].remaining,900);
assert.equal(M.usedAmount(state,'spa','spa-body'),100n);
assert.equal(M.recordPaid(state,'spa'),200000n);
assert.equal(M.summary(state).payments,initial.payments);
assert.deepEqual(original,createFixtures(),'Operations do not mutate fixtures or caller state');
state=M.undoOperation(state,state.events.at(-1).id);
assert.equal(get('spa').entitlements[0].remaining,1000);
assert.equal(state.events.at(-1).undone,true);
assert.equal(M.usedAmount(state,'spa','spa-body'),0n);
state=M.applyOperation(state,'coffee',{type:'use',date:day,values:{'coffee-money':3500}},1);
assert.equal(get('coffee').entitlements[0].remaining,16500);
assert.equal(M.usedAmount(state,'coffee','coffee-money'),3500n);
assert.equal(M.recordPaid(state,'coffee'),20000n);
assert.throws(()=>M.applyOperation(state,'coffee',{type:'use',date:day,values:{'coffee-money':20000}},2),/不足/);
assert.throws(()=>M.applyOperation(state,'coffee',{type:'use',date:day,values:{'coffee-money':100}},1),/变更/);
state=M.applyOperation(state,'combo',{type:'topup',date:day,paid:100000,values:{'combo-money':20000,'combo-spa':300}},1);
assert.deepEqual(get('combo').entitlements.map(e=>e.remaining),[70000,800]);
assert.equal(M.recordPaid(state,'combo'),300000n);
const topupId=state.events.at(-1).id;
state=M.undoOperation(state,topupId);
assert.deepEqual(get('combo').entitlements.map(e=>e.remaining),[50000,500]);
assert.equal(M.recordPaid(state,'combo'),200000n);
const directUpdate=M.applyOperation(state,'combo',{type:'adjust',date:day,values:{'combo-money':51000},note:''},get('combo').revision);assert.equal(directUpdate.records.find(r=>r.id==='combo').entitlements[0].remaining,51000);assert.equal(M.usedAmount(directUpdate,'combo','combo-money'),0n);
state=M.applyOperation(state,'combo',{type:'adjust',date:day,values:{'combo-money':51000},note:'与商家核对'},get('combo').revision);
assert.equal(M.recordPaid(state,'combo'),200000n);
const oldDate=get('cloud').expires;
state=M.applyOperation(state,'cloud',{type:'renew',date:day,paid:100000,nextDate:M.addCycle(oldDate,{unit:'year',value:1}),updateFee:false},1);
assert.equal(get('cloud').fee,120000);
assert.equal(M.recordPaid(state,'cloud'),220000n);
assert.notEqual(get('cloud').expires,oldDate);
state=M.undoOperation(state,state.events.at(-1).id);
assert.equal(get('cloud').expires,oldDate);
assert.equal(M.recordPaid(state,'cloud'),120000n);
assert.equal(M.addCycle('2027-01-31',{unit:'month',value:1}),'2027-02-28');
assert.equal(M.addCycle('2027-02-28',{unit:'month',value:1},31),'2027-03-31');
assert.equal(M.addCycle('2024-02-29',{unit:'year',value:1}),'2025-02-28');
assert.equal(M.equivalent(120000,{unit:'year',value:1}),10000n);
assert.equal(M.equivalent(120000,{unit:'year',value:1},'year'),120000n);
assert.equal(M.equivalent(null,{unit:'month',value:1}),null);
assert.equal(M.equivalent(48000,null),null);
assert.equal(M.equivalent(0,{unit:'month',value:1}),0n);
for(const raw of ['1e3','-1','1.001','NaN','Infinity',''])assert.throws(()=>M.decimal(raw));
assert.equal(M.decimal('0'),0);
assert.equal(M.decimal('2000'),200000);
assert.throws(()=>M.decimal('90000000000.01'));
assert.throws(()=>M.applyOperation(state,'spa',{type:'topup',date:day,paid:200000,values:{}},get('spa').revision),/至少/);
const newCard={id:'new-spa',kind:'stored',name:'新 SPA',entitlements:[{id:'new-spa-units',kind:'quantity',name:'护理',unit:'次',remaining:1000}],expires:'',note:''};
assert.throws(()=>M.createRecord(state,newCard,{date:day}),/支付/);
state=M.createRecord(state,newCard,{date:day,paid:200000});
assert.equal(get('new-spa').entitlements.length,1);
assert.equal(get('new-spa').entitlements[0].kind,'quantity');
assert.equal(M.recordPaid(state,'new-spa'),200000n);
const partiallyUsed={...newCard,id:'partly-used',entitlements:[{id:'partly',kind:'quantity',name:'护理',unit:'次',acquired:1000,remaining:600}]};
state=M.createRecord(state,partiallyUsed,{date:day,paid:200000});assert.equal(M.usedAmount(state,'partly-used','partly'),0n);assert.equal(get('partly-used').entitlements[0].remaining,600);assert.match(state.events.at(-1).summary,/购买.*10 次.*当前剩余 6 次/);
const legacyBefore=structuredClone(get('legacy')),legacyEvents=state.events.filter(e=>e.recordId==='legacy');
state=M.editRecord(state,'new-spa',{note:'明确修改新卡'},1);
assert.deepEqual(get('legacy'),legacyBefore);
assert.deepEqual(state.events.filter(e=>e.recordId==='legacy'),legacyEvents);
assert.equal(M.recordPaid(state,'legacy'),null);
const unknownCard={...newCard,id:'existing',name:'已有记录'};
state=M.createRecord(state,unknownCard,{date:day,paid:null,existing:true});
assert.equal(M.recordPaid(state,'existing'),null);
const unknownBalance={...newCard,id:'unknown-existing',name:'旧余额未知',entitlements:[{id:'unknown',kind:'money',name:'余额',remaining:null,unit:'元'}]};
state=M.createRecord(state,unknownBalance,{date:day,paid:null,existing:true});
assert.equal(get('unknown-existing').entitlements[0].remaining,null);
state=M.createRecord(state,{...newCard,id:'unknown-quantity',entitlements:[{id:'q',kind:'quantity',name:'旧课时',remaining:null,unit:'节'}]},{date:day,paid:null,existing:true});
assert.match(state.events.at(-1).summary,/未记录/);
assert.throws(()=>M.createRecord(state,{...unknownBalance,id:'unknown-new'},{date:day,paid:10000}),/权益数量/);
assert.throws(()=>M.applyOperation(state,'unknown-existing',{type:'use',date:day,values:{unknown:100}},1),/未知/);
state=M.applyOperation(state,'unknown-existing',{type:'adjust',date:day,values:{unknown:10000},note:'用户确认'},1);
assert.equal(get('unknown-existing').entitlements[0].remaining,10000);
const originalCost=M.summary(state).payments;
state=M.archiveRecord(state,'new-spa',true);
assert.equal(M.summary(state).payments,originalCost,'Archive does not erase actual recorded payments');
assert.throws(()=>M.applyOperation(state,'new-spa',{type:'use',date:day,values:{'new-spa-units':100}},get('new-spa').revision),/变更/);
state=M.archiveRecord(state,'new-spa',false);
assert.equal(get('new-spa').entitlements[0].remaining,1000);
assert.equal(M.upcoming(state).some(r=>r.id==='lessons'),false);
assert.equal(M.upcoming(state).filter(r=>r.id==='combo').length,1);
console.log('PASS prototype model: cost/rights separation, combined entitlements, use/topup/adjust/undo, real payment statistics, unknown vs zero, precise cycles, month-end dates, immutability, archive and manual renewal.');
